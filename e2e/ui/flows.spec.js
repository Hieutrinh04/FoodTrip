import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { mockBackend } from '../fixtures/backend.js'
import { tripId } from '../fixtures/data.js'

async function wizard(page) {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('link', { name: 'Bắt đầu miễn phí', exact: true }).first().click()
  await page.getByRole('button', { name: 'Hà Nội Hà Nội', exact: true }).click()
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Khi nào, đi bao lâu và với ngân sách nào?' })).toBeVisible()
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bạn muốn đi tự túc hay có tour dẫn đường?' })).toBeVisible()
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
  await page.getByRole('button', { name: 'Bỏ qua, chọn sau', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bạn thích điều gì?' })).toBeVisible()
  await page.getByRole('button', { name: 'Tạo lịch trình', exact: true }).click()
}

test('khách đi qua wizard tới chốt đăng nhập trước khi tạo lịch', async ({ page }) => {
  const mock = await mockBackend(page)
  await wizard(page)
  await expect(page.locator('.ft-auth-dialog')).toBeVisible()
  expect(mock.writes).toEqual([])
  mock.assertNoErrors()
})

test('session giả: tạo, lưu, mở link chia sẻ bằng RPC, và mở /account', async ({ page }) => {
  const mock = await mockBackend(page, { role: 'customer' })
  await wizard(page)
  await expect(page.getByText('Lịch trình Hà Nội đã sẵn sàng!', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Lưu lịch trình', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Đã lưu', exact: true })).toBeVisible()
  expect(mock.writes[0].body.user_id).toBeTruthy()
  expect(mock.writes[0].body.days.length).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Chia sẻ cho bạn bè', exact: true }).click()
  await expect.poll(() => mock.writes.filter((w) => w.body?.is_public === true).length).toBe(1)
  await page.goto(`/trip/${tripId}`, { waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Lịch trình được chia sẻ', { exact: true })).toBeVisible()
  expect(mock.requests.some((r) => r.path.endsWith('/rpc/shared_itinerary'))).toBe(true)
  await page.goto('/account', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await expect(page.getByText('customer@example.test', { exact: true }).first()).toBeVisible()
  mock.assertNoErrors()
})

