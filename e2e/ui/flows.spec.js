test('trợ lý fixture: tìm món, hỏi lại điểm đến, chuyển nhân viên với transcript', async ({ page }) => {
  const mock = await mockBackend(page)
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Trợ lý FoodTrip', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Trợ lý FoodTrip' })
  const input = dialog.getByRole('textbox', { name: 'Nhập câu hỏi hoặc yêu cầu lên lịch…' })
  await input.fill('tìm quán bún chả')
  await dialog.getByRole('button', { name: 'Gửi', exact: true }).click()
  await expect(dialog.getByText(/ở thành phố nào/)).toBeVisible()
  await input.fill('quán phở ở Hà Nội')
  await dialog.getByRole('button', { name: 'Gửi', exact: true }).click()
  await expect(dialog.getByText('Phở kiểm thử', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Gặp nhân viên hỗ trợ', exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Tên của bạn' }).fill('Khách giả lập')
  await dialog.getByRole('textbox', { name: 'Email nhận trả lời' }).fill('fixture@example.test')
  await dialog.getByRole('button', { name: 'Gửi cho nhân viên', exact: true }).click()
  await expect.poll(() => mock.writes.length).toBe(1)
  expect(mock.writes[0].body.source).toBe('assistant')
  expect(mock.writes[0].body.transcript.some((m) => m.from === 'user' && m.text === 'quán phở ở Hà Nội')).toBe(true)
  mock.assertNoErrors()
})

