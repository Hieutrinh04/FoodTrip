const customPlacesRegistry = new Map()

// Places sourced live from Google Places for a destination outside the
// curated dataset (see citySearch.js) aren't in the static PLACES array —
// registering them here lets getPlace() find them transparently so
// ItineraryTicket/LiveTripMap/PlaceDetail don't need any special-casing.
export function registerCustomPlaces(places) {
  for (const p of places) customPlacesRegistry.set(p.id, p)
}

export function getPlace(id) {
  return PLACES.find((p) => p.id === id) ?? customPlacesRegistry.get(id)
}

export function getPlacesByCity(cityId) {
  return PLACES.filter((p) => p.city === cityId)
}

