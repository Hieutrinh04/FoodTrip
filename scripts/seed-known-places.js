// Writes the seed rows of public.known_places (the venues detect-place can
// recognise in a caption without a map search) from ml/real-places.json —
// real Google Maps venues, food and cafes only. They have no coordinates yet;
// detect-place fills them in the first time one is matched.
//
// Usage: node scripts/seed-known-places.js > supabase/migrations/<ts>_known_places_seed.sql

import { readFileSync } from 'node:fs'
import { coreName } from '../supabase/functions/_shared/placeNames.js'

const places = JSON.parse(readFileSync(new URL('../ml/real-places.json', import.meta.url), 'utf8'))
const quote = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const rows = []
const seen = new Set()
for (const p of places) {
  if (!['food', 'cafe'].includes(p.category) || !p.id || !p.name || seen.has(p.id)) continue
  seen.add(p.id)
  rows.push(`(${quote(p.id)}, ${quote(p.name)}, ${quote(coreName(p.name))}, ${quote(p.address)}, ${quote(p.cityName)}, 'seed')`)
}
console.log(`-- Seed of public.known_places: ${rows.length} real food and cafe venues from ml/real-places.json
-- (generated by scripts/seed-known-places.js). Coordinates come later, from the
-- first map search that confirms each one.

begin;

insert into public.known_places (place_id, name, core, address, city, source) values
${rows.join(',\n')}
on conflict (place_id) do nothing;

commit;`)
